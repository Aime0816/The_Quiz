<?php
header("Cache-Control: no-store");
header("Referrer-Policy: no-referrer");
header("X-Content-Type-Options: nosniff");
// A missing viewer token must never turn the projector route into a staff screen.
$token = $_GET['view'] ?? '';
if (!is_string($token) || !preg_match('/^[a-f0-9]{48}$/', $token)) {
    http_response_code(400);
    exit('Open the audience link generated by the marker for this competition.');
}
// Give the audience a dedicated URL while reusing the compiled quiz application.
$page = file_get_contents(__DIR__ . "/../play/index.html");
if ($page === false) {
    http_response_code(503);
    exit("The live screen is unavailable. Build the frontend first.");
}
echo str_replace("./assets/", "../play/assets/", $page);
